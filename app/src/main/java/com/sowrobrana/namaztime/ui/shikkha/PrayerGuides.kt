private fun guide(name: String, rakats: String, niyat: String, notes: List<String>): PrayerGuide {
    val niyatStep = GuideStep(
        title = "নিয়ত",
        posture = Posture.QIYAM,
        body = "নিয়ত মনের সংকল্প — মুখে বলা জরুরি নয়, তবে মনে রাখতে সুবিধা হয় বলে অনেকে মুখে বলেন। এই নামাজের নিয়ত:",
        recitation = niyat,
        meaning = null,
    )
    return PrayerGuide(name, rakats, niyat, listOf(niyatStep) + commonSteps(), notes)
}

